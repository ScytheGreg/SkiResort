package simulation;

import athlete.Athlete;
import containers.Queue;
import resort.Edge;

import java.time.LocalTime;

/**
 * Represents the moment an athlete arrives at the bottom of a lift
 * and joins the waiting line (FIFO queue).
 */
public class QueueUp extends AthleteEvent {

    public QueueUp(LocalTime time, Athlete athlete, Edge edge) {
        super(time, athlete, edge);
    }

    /**
     * Executes the queuing logic.
     * 1. Logs the arrival at the lift line if the athlete is tracked.
     * 2. Adds the athlete to the specific lift's internal waiting structure.
     * * Note: This event does NOT return a future event immediately because
     * the athlete's next action depends on the lift's capacity and frequency.
     * * @param seed Random seed (inherited from Event, not used here).
     * @return An empty Queue (the next event will be generated by the SkiLift).
     */
    @Override
    public Queue performAction(int seed) {
        // Log the activity (e.g., "At 10:00:00 athlete 1 has queued up...")
        Queue result = super.performAction(seed);

        /* * Logic: The athlete enters the lift's queue.
         * The athlete will remain in this "limbo" until a
         * PickUpPassengers event processes them.
         */
        getAthlete().queueUp(getEdge());

        return result;
    }

    /**
     * Formats the log message.
     * Example: "At 09:45:12 the athlete nr     5 has queued up to lift    nr 2"
     */
    @Override
    public String toString() {
        // "has queued up to" is phrased to match the length of "has begun ride on"
        return super.toString() + " has queued up to " + getEdge().getName() + "  nr " + getEdge().getId();
    }
}