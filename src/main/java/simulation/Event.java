package simulation;

import containers.Queue;

import java.time.LocalTime;
import java.time.format.DateTimeFormatter;

/**
 * Base class for all actions that occur within the simulation.
 * Events are stored in a PriorityQueue and processed in chronological order.
 */
abstract public class Event {
    // The specific time this event is scheduled to occur
    private LocalTime takePlaceTime;

    // Standard format for log output as required by the project (HH:mm:ss)
    private static final DateTimeFormatter FORMATTER =
            DateTimeFormatter.ofPattern("HH:mm:ss");

    public Event(LocalTime time) {
        takePlaceTime = time;
    }

    public LocalTime getTime() {
        return takePlaceTime;
    }

    /**
     * Updates the event time.
     * Useful for events created with a null time (like an athlete waiting for a lift)
     * that get assigned a time once they reach the front of the queue.
     */
    public void setTime(LocalTime time) {
        takePlaceTime = time;
    }

    /**
     * Executes the logic associated with this event.
     * * @param seed A random seed used to ensure deterministic but varied behavior.
     * @return A Queue of new Events generated by this action (e.g., finishing
     * a ride creates a new decision event).
     */
    abstract public Queue performAction(int seed);

    /**
     * Returns a string representation of the event time.
     * Used for logging athlete activities when 'isTracked' is true.
     */
    @Override
    public String toString() {
        return "At " + takePlaceTime.format(FORMATTER);
    }
}